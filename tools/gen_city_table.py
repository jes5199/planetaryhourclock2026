#!/usr/bin/env python3
"""Generate firmware/src/city_table.inc from GeoNames' cities15000 list.

Data: GeoNames (https://www.geonames.org), licensed CC BY 4.0
(https://creativecommons.org/licenses/by/4.0/). Cities with population over 15,000.

Run from the repo root:  python3 tools/gen_city_table.py
Downloads into tools/data/geonames/ (git-ignored) if the files are missing.
"""
import csv
import io
import pathlib
import urllib.request
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "tools/data/geonames"
BASE = "https://download.geonames.org/export/dump/"
OUT = ROOT / "firmware/src/city_table.inc"

# Old zone names GeoNames may use, mapped to the names in the posix_tz_db table.
TZ_ALIASES = {
    "Asia/Calcutta": "Asia/Kolkata", "Asia/Saigon": "Asia/Ho_Chi_Minh",
    "Asia/Katmandu": "Asia/Kathmandu", "Asia/Rangoon": "Asia/Yangon",
    "Europe/Kyiv": "Europe/Kiev", "Pacific/Kanton": "Pacific/Enderbury",
    "America/Indianapolis": "America/Indiana/Indianapolis",
}


def fetch(name):
    path = DATA / name
    if not path.exists():
        DATA.mkdir(parents=True, exist_ok=True)
        print(f"downloading {name}")
        urllib.request.urlretrieve(BASE + name, path)
    return path


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("?", "\\?") + '"'


def main():
    with zipfile.ZipFile(fetch("cities15000.zip")) as z:
        cities_txt = z.read("cities15000.txt").decode("utf-8")

    admin1 = {}
    for line in fetch("admin1CodesASCII.txt").read_text(encoding="utf-8").splitlines():
        code, name, _ascii, _id = line.split("\t")
        admin1[code] = name

    countries = {}
    for line in fetch("countryInfo.txt").read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        f = line.split("\t")
        countries[f[0]] = f[4]

    zones = sorted(row[0] for row in csv.reader(open(ROOT / "tools/data/posix_tz_db/zones.csv", newline="")))
    zone_index = {z: i for i, z in enumerate(zones)}

    rows = []
    for f in csv.reader(io.StringIO(cities_txt), delimiter="\t", quoting=csv.QUOTE_NONE):
        name, ascii_name = f[1], f[2]
        lat, lon = float(f[4]), float(f[5])
        cc, a1 = f[8], f[10]
        pop = int(f[14] or 0)
        tz = TZ_ALIASES.get(f[17], f[17])
        rows.append((pop, name, ascii_name, admin1.get(f"{cc}.{a1}", ""), cc, lat, lon, zone_index.get(tz, -1)))
    rows.sort(key=lambda r: (-r[0], r[1]))  # biggest first, so searches list them first

    region_names = sorted({r[3] for r in rows})
    region_index = {n: i for i, n in enumerate(region_names)}
    country_codes = sorted({r[4] for r in rows})
    country_index = {c: i for i, c in enumerate(country_codes)}

    with open(OUT, "w", encoding="utf-8") as out:
        out.write("// Generated by tools/gen_city_table.py from GeoNames cities15000. Do not edit.\n")
        out.write("// Data (c) GeoNames, CC BY 4.0: https://www.geonames.org\n")
        out.write(f"// {len(rows)} cities, sorted by population (largest first).\n\n")
        out.write("static const char* const kRegions[] = {\n")
        for n in region_names:
            out.write(f"  {c_str(n)},\n")
        out.write("};\n\nstatic const char* const kCountries[][2] = {\n")
        for c in country_codes:
            out.write(f"  {{{c_str(c)}, {c_str(countries.get(c, c))}}},\n")
        out.write("};\n\nstatic const City kCities[] = {\n")
        for pop, name, ascii_name, region, cc, lat, lon, tzi in rows:
            search = ascii_name.lower()
            out.write(f"  {{{c_str(name)}, {c_str(search)}, {region_index[region]}, {country_index[cc]}, "
                      f"{lat:.4f}f, {lon:.4f}f, {pop}u, {tzi}}},\n")
        out.write("};\n")
    print(f"wrote {len(rows)} cities, {len(region_names)} regions, {len(country_codes)} countries "
          f"to {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
