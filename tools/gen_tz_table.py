#!/usr/bin/env python3
"""Generate firmware/src/tz_table.inc from tools/data/posix_tz_db/zones.csv.

zones.csv comes from https://github.com/nayarsystems/posix_tz_db (MIT): IANA zone
name -> POSIX TZ string. Run from the repo root: python3 tools/gen_tz_table.py
"""
import csv
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
rows = sorted(csv.reader(open(root / "tools/data/posix_tz_db/zones.csv", newline="")))
out = root / "firmware/src/tz_table.inc"
with open(out, "w") as f:
    f.write("// Generated by tools/gen_tz_table.py from posix_tz_db (MIT). Do not edit.\n")
    f.write("// Sorted by IANA name for binary search.\n")
    for name, posix in rows:
        f.write(f'{{"{name}", "{posix}"}},\n')
print(f"wrote {len(rows)} zones to {out.relative_to(root)}")
